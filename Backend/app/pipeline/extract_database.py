"""Source 2 - database: companies already followed in UIMM Boost, with their diagnostic scores.

The SQL is written by hand (not generated by the ORM) so that the selection, joins and
filters are explicit and documented, and so it can be checked with EXPLAIN in PostgreSQL.
"""
import logging

from sqlalchemy import text

logger = logging.getLogger("pipeline.database")

# Selection: only the columns the dataset needs (no contact name, e-mail or phone: personal data).
# Joins:     LEFT JOIN keeps companies that have no score yet (scored_axes = 0).
#            The sub-select limits scores to active axes, so the retired Finance axis is ignored.
# Filters:   real companies only (no archived or synthetic demo companies), and only those with a SIREN.
# Grouping:  one row per company, with the average maturity percentage over its scored axes.
# Indexes:   ix_companies_siren (WHERE siren IS NOT NULL) and ix_scores_company_id (join on company_id).
COMPANIES_WITH_SCORES_SQL = text("""
    SELECT
        c.id                    AS company_id,
        c.name                  AS company_name,
        c.siren                 AS siren,
        COUNT(s.id)             AS scored_axes,
        AVG(s.score_percentage) AS avg_score_percentage
    FROM companies AS c
    LEFT JOIN scores AS s
           ON s.company_id = c.id
          AND s.axis_id IN (SELECT a.id FROM axes AS a WHERE a.is_active = TRUE)
    WHERE c.siren IS NOT NULL
      AND c.is_archived = FALSE
      AND c.is_synthetic = FALSE
    GROUP BY c.id, c.name, c.siren
    ORDER BY c.id
""")


def extract_database(connection) -> list[dict]:
    """Run the extraction query on an open SQLAlchemy connection or session."""
    rows = [dict(row._mapping) for row in connection.execute(COMPANIES_WITH_SCORES_SQL)]
    for row in rows:
        average = row["avg_score_percentage"]
        row["avg_score_percentage"] = round(float(average), 1) if average is not None else None
    logger.info("Database source: %s companies with a SIREN found in UIMM Boost", len(rows))
    return rows
